'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(process.argv[2]||path.join(__dirname,'..'));
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const app=read('app.html'),coordinator=read('modules/write-coordinator.js'),storage=read('modules/storage.js'),secure=read('modules/secure-backup.js'),historical=read('modules/historical-import.js');
assert.ok(app.indexOf('modules/write-coordinator.js')<app.indexOf('modules/storage.js'),'el coordinador debe cargarse antes de storage.js');
assert.match(coordinator,/Storage\.prototype\.setItem/);
assert.match(coordinator,/queueMutation\('set'/);
assert.match(coordinator,/JOURNAL_REGISTRY_KEY/);
assert.match(coordinator,/PERSISTENCE_PENDING_WRITE_REJECTED/);
assert.match(coordinator,/readJournal\(journalKey\)\.some/);
assert.match(coordinator,/REPLAY_LOCK_KEY/);
assert.match(coordinator,/acknowledgeJournalEvent/);
assert.match(coordinator,/PERSISTENCE_PENDING_APPLY_VERIFY_FAILED/);
assert.match(coordinator,/PERSISTENCE_REPLAY_IN_PROGRESS/);
assert.doesNotMatch(coordinator,/keys\.forEach\(key => nativeRemove\.call\(local\(\), key\)\)/,'no se pueden borrar journals completos desde una lista obsoleta');
assert.match(coordinator,/waitForWritable/);
assert.match(storage,/awaitWritePermission\(options\)/);
assert.match(storage,/replaceRawDatabase\(raw, options = \{\}\)/);
assert.match(secure,/coordinationToken/);
assert.match(secure,/authorizedSetItem/);
assert.match(historical,/immediatelyBeforeRestore/);
assert.match(historical,/CONCURRENT_WRITE_DETECTED_IMPORT_ABORTED/);
assert.match(historical,/CONCURRENT_WRITE_ROLLED_BACK/);
console.log('Write coordinator contract PASS: HX07-HX09 coordinate fences, durable journals and per-event acknowledgements.');
